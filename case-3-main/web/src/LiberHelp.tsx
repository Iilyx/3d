export function LiberHelp() {
  const [open, setOpen] = useState(false);
  const panelId = useId();

  useEffect(() => {
    if (!open) return;
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") setOpen(false);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open]);

  return (
    <div className="liber-help">
      <button
        type="button"
        className={open ? "is-on" : ""}
        aria-label="Ограничения Liber"
        aria-expanded={open}
        aria-controls={panelId}
        onClick={() => setOpen((v) => !v)}
      >
        <IconHelp size={16} />
      </button>
      {open ? (
        <div className="liber-help-panel" id={panelId} role="dialog" aria-label="Ограничения Liber">
          <p className="liber-help-lead">
            Liber собирает отчёт, схему или презентацию по вашим данным и документам. Сам числа не придумывает.
          </p>
          {GROUPS.map((group) => (
            <section key={group.title}>
              <h3>{group.title}</h3>
              <ul>
                {group.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ul>
            </section>
          ))}
        </div>
      ) : null}
    </div>
  );
}
