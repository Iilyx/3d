export function starterPromptForStructure(structureId?: string | null): string {
  const id = (structureId || "").trim();
  const card = DECK_TEMPLATE_CARDS.find((c) => c.structureId === id);
  return (
    card?.starterPrompt ||
    EXTRA_STARTER_PROMPTS[id] ||
    "Собери презентацию 16:9 по материалам ниже. Структура ясная, цифры только из документа или текста запроса — ничего не выдумывай."
  );
}
